// Makes src/theme.css from the web client's own Theme.cs, so the overworld's HUD and the card layer it opens over can
// never drift apart in color: every `public static readonly Color Name = FromHex("#rrggbb")` becomes the CSS variable
// `--name`. It also copies the client's fonts (content/res/fonts) to public/fonts, for the same faces.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const themeCs = readFileSync(join(root, "dotnet", "src", "Cantrip.Client.Web", "Theme.cs"), "utf8");

const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const tokens = [...themeCs.matchAll(/public static readonly Color (\w+) = FromHex\("(#[0-9a-fA-F]{6,8})"\);/g)]
  .map(([, name, hex]) => `  --${kebab(name)}: ${hex.toLowerCase()};`);
if (tokens.length === 0) {
  throw new Error("theme.mjs: no colors found in Theme.cs");
}

const fonts = [
  ["Beleren", "beleren-bold_P1.01.ttf", 700],
  ["MPlantin", "mplantin.ttf", 400],
];
mkdirSync(join(here, "..", "public", "fonts"), { recursive: true });
for (const [, file] of fonts) {
  copyFileSync(join(root, "content", "res", "fonts", file), join(here, "..", "public", "fonts", file));
}

const css = `/* Generated by scripts/theme.mjs from dotnet/src/Cantrip.Client.Web/Theme.cs - do not edit. */
:root {
${tokens.join("\n")}
}
${fonts
  .map(([family, file, weight]) => `
@font-face {
  font-family: "${family}";
  src: url("/fonts/${file}") format("truetype");
  font-weight: ${weight};
  font-display: swap;
}`)
  .join("\n")}
`;
writeFileSync(join(here, "..", "src", "theme.css"), css);
console.log(`theme.mjs: ${tokens.length} colors, ${fonts.length} fonts`);
